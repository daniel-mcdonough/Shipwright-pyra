// Unit test for the combiner range analysis. The functions under test are lifted verbatim out of
// gfx_opengl.cpp at build time (see offline-shader-checks.sh), so this tests the shipped text
// rather than a paraphrase of it.
#include <cstdio>
#include <cstring>

enum {
    SHADER_0, SHADER_INPUT_1, SHADER_INPUT_2, SHADER_INPUT_3, SHADER_INPUT_4,
    SHADER_INPUT_5, SHADER_INPUT_6, SHADER_INPUT_7, SHADER_TEXEL0, SHADER_TEXEL0A,
    SHADER_TEXEL1, SHADER_TEXEL1A, SHADER_1, SHADER_COMBINED, SHADER_NOISE
};
enum { SHADER_OPT_ELIDE_NOOP_WRAP = 1 };

struct CCFeatures {
    int c[2][2][4];
    bool opt_alpha, opt_2cyc;
    bool do_single[2][2], do_multiply[2][2], do_mix[2][2], color_alpha_same[2];
};

#include "range_extracted.inc" // generated by offline-shader-checks.sh

static int failures = 0;

// Fills in do_single/do_multiply/do_mix the way gfx_cc_get_features does, so a case is written as
// the four operands it really is rather than as the conclusion under test.
static void Derive(CCFeatures& cc) {
    for (int c = 0; c < 2; c++) {
        for (int i = 0; i < 2; i++) {
            cc.do_single[c][i] = cc.c[c][i][2] == SHADER_0;
            cc.do_multiply[c][i] = cc.c[c][i][1] == SHADER_0 && cc.c[c][i][3] == SHADER_0;
            cc.do_mix[c][i] = cc.c[c][i][1] == cc.c[c][i][3];
        }
        cc.color_alpha_same[c] = memcmp(cc.c[c][0], cc.c[c][1], sizeof(cc.c[c][0])) == 0;
    }
}

static void Check(const char* name, CCFeatures cc, bool wantMid, bool wantOut) {
    Derive(cc);
    const bool mid = !CombinerCycleInRangeFor(cc, SHADER_OPT_ELIDE_NOOP_WRAP, false);
    const bool out = !CombinerCycleInRangeFor(cc, SHADER_OPT_ELIDE_NOOP_WRAP, true);
    const bool ok = mid == wantMid && out == wantOut;
    if (!ok) {
        failures++;
    }
    printf("%-46s wrap_mid=%d (want %d)  wrap_out=%d (want %d)  %s\n", name, mid, wantMid, out,
           wantOut, ok ? "ok" : "FAIL");
}

int main() {
    // (A - B) * C + D, per cycle, per channel. Cycle 1 is ignored unless opt_2cyc.
    const int MUL[4] = { SHADER_TEXEL0, SHADER_0, SHADER_INPUT_1, SHADER_0 };       // TEXEL0 * SHADE
    const int SINGLE[4] = { SHADER_0, SHADER_0, SHADER_0, SHADER_TEXEL0 };          // TEXEL0
    const int MIX[4] = { SHADER_TEXEL0, SHADER_INPUT_1, SHADER_INPUT_2, SHADER_INPUT_1 };
    const int FULL[4] = { SHADER_TEXEL0, SHADER_TEXEL1, SHADER_INPUT_1, SHADER_INPUT_2 };
    const int MUL_COMB[4] = { SHADER_COMBINED, SHADER_0, SHADER_INPUT_1, SHADER_0 };
    const int SINGLE_COMB[4] = { SHADER_0, SHADER_0, SHADER_0, SHADER_COMBINED };

    auto make = [](const int* c0col, const int* c0a, const int* c1col, const int* c1a, bool alpha,
                   bool twocyc) {
        CCFeatures cc{};
        memcpy(cc.c[0][0], c0col, sizeof(cc.c[0][0]));
        memcpy(cc.c[0][1], c0a, sizeof(cc.c[0][1]));
        memcpy(cc.c[1][0], c1col, sizeof(cc.c[1][0]));
        memcpy(cc.c[1][1], c1a, sizeof(cc.c[1][1]));
        cc.opt_alpha = alpha;
        cc.opt_2cyc = twocyc;
        return cc;
    };

    // One cycle. wrap_mid is never emitted for these (the template only reaches it at c == 1),
    // but the analysis still reports on cycle 0, so it is checked.
    Check("1cyc multiply", make(MUL, MUL, MUL, MUL, true, false), false, false);
    Check("1cyc single", make(SINGLE, SINGLE, SINGLE, SINGLE, true, false), false, false);
    Check("1cyc mix", make(MIX, MIX, MIX, MIX, true, false), false, false);
    Check("1cyc full form", make(FULL, FULL, FULL, FULL, true, false), true, true);
    Check("1cyc no alpha, multiply", make(MUL, FULL, MUL, MUL, false, false), false, false);
    // Alpha differs from colour and is the full form: the whole cycle is out of range, because
    // the shader wraps the vec4 as one.
    Check("1cyc colour reduced, alpha full", make(MUL, FULL, MUL, MUL, true, false), true, true);

    // Two cycles.
    Check("2cyc reduced then reduced", make(MUL, MUL, MUL_COMB, MUL_COMB, true, true), false, false);
    Check("2cyc full then reduced", make(FULL, FULL, MUL_COMB, MUL_COMB, true, true), true, true);
    Check("2cyc reduced then full", make(MUL, MUL, FULL, FULL, true, true), false, true);
    Check("2cyc reduced, cycle 1 passes combined", make(MUL, MUL, SINGLE_COMB, SINGLE_COMB, true, true),
          false, false);
    // Cycle 0 naming COMBINED reads an uninitialised texel, so it is never in range.
    Check("1cyc single of combined", make(SINGLE_COMB, SINGLE_COMB, MUL, MUL, true, false), true, true);

    // With the bit clear nothing may be elided, whatever the combiner is.
    CCFeatures off = make(MUL, MUL, MUL, MUL, true, false);
    Derive(off);
    if (CombinerCycleInRangeFor(off, 0, false) || CombinerCycleInRangeFor(off, 0, true)) {
        printf("%-46s FAIL\n", "opt bit clear keeps both wraps");
        failures++;
    } else {
        printf("%-46s ok\n", "opt bit clear keeps both wraps");
    }

    printf("\n%s\n", failures ? "FAILURES" : "all ok");
    return failures != 0;
}
